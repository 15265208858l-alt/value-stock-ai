"""
ValueStock AI
最终投资决策模块 V16.4

根据：

1. 综合投资评分
2. 当前估值
3. 历史估值
4. 风险等级

输出最终投资决策：

建仓
等待
观察
回避
"""


# =========================================================
# 最终投资决策
# =========================================================

def make_investment_decision(
    investment_score,
    valuation_level,
    historical_level,
    risk_level
):

    # -----------------------------------------------------
    # 1. 基础容错
    # -----------------------------------------------------

    try:
        investment_score = float(investment_score)

    except (TypeError, ValueError):

        investment_score = 0


    valuation_level = str(
        valuation_level or "数据不足"
    )

    historical_level = str(
        historical_level or "数据不足"
    )

    risk_level = str(
        risk_level or "数据不足"
    )


    # =====================================================
    # 2. 高风险优先判断
    # =====================================================

    if risk_level == "高风险":

        return {
            "decision": "🔴 原则上回避",
            "action": "暂不买入",
            "position": "0%",
            "reason": (
                "当前风险水平较高，即使估值具有一定吸引力，"
                "也不符合长期价值投资的风险控制原则。"
            )
        }


    # =====================================================
    # 3. 优质公司 + 低估
    # =====================================================

    if (
        investment_score >= 80
        and valuation_level in [
            "明显低估",
            "较低估值",
            "偏低估值"
        ]
        and risk_level in [
            "低风险",
            "风险较低"
        ]
    ):

        return {
            "decision": "🟢 可以分批建仓",
            "action": "开始分批买入",
            "position": "20%—30%",
            "reason": (
                "综合评分较高，公司质量较好，"
                "当前估值具有一定安全边际，"
                "同时整体风险处于较低水平。"
            )
        }


    # =====================================================
    # 4. 优质公司 + 合理估值
    # =====================================================

    if (
        investment_score >= 75
        and valuation_level == "合理附近"
        and risk_level != "风险较高"
    ):

        return {
            "decision": "🟡 可以小仓关注",
            "action": "少量分批建仓",
            "position": "10%—20%",
            "reason": (
                "公司综合质量较好，但当前估值安全边际一般。"
                "适合小仓位建立观察仓，不建议一次性重仓。"
            )
        }


    # =====================================================
    # 5. 公司优秀，但估值偏高
    # =====================================================

    if (
        investment_score >= 75
        and valuation_level in [
            "偏高估值",
            "明显偏高",
            "高估"
        ]
    ):

        return {
            "decision": "🟡 等待更好价格",
            "action": "暂不追高",
            "position": "0%—10%",
            "reason": (
                "公司综合质量较好，但当前估值已经缺乏足够安全边际。"
                "建议加入长期观察名单，等待价格回落或业绩继续增长。"
            )
        }


    # =====================================================
    # 6. 中等质量公司
    # =====================================================

    if investment_score >= 60:

        return {
            "decision": "🟠 谨慎观察",
            "action": "暂不重仓",
            "position": "0%—10%",
            "reason": (
                "公司具备一定投资价值，但综合优势尚不明显。"
                "建议继续观察财务质量、现金流、风险和估值变化。"
            )
        }


    # =====================================================
    # 7. 低分公司
    # =====================================================

    return {
        "decision": "🔴 暂不考虑",
        "action": "不建议买入",
        "position": "0%",
        "reason": (
            "综合投资评分较低，当前尚未达到长期价值投资系统的筛选标准。"
        )
    }
